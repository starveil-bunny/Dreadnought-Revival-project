#!/usr/bin/env python3
"""Generate battle-server-mod/src/npc_abilities.h: Havoc NPC ShipId -> the
ability classes its YNPCPawnDataEntry row gives it, from the cooked dataset
(data/pve/HVC_DeadHorde_EnemyShips_rows.jsonl, `bpdump --rows` of
Maps/Havoc/HVC_DeadHorde_EnemyShips.uasset).

/spawn creates these pawns directly, without the dataset spawn that installs
the row's abilities, so the host installs them itself. A ShipId listed twice
(DreadnoughtHeavyNukerT5) keeps its first row.

Usage: python3 scripts/gen-npc-abilities.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data/pve/HVC_DeadHorde_EnemyShips_rows.jsonl")
OUT = os.path.join(ROOT, "battle-server-mod/src/npc_abilities.h")
SLOTS = ["m_primaryAbility", "m_secondaryAbility", "m_perimeterAbility", "m_internalAbility",
         "m_extraNPCAbility1", "m_extraNPCAbility2", "m_extraNPCAbility3", "m_extraNPCAbility4"]

rows = {}
for line in open(SRC):
    for e in json.loads(line).get("m_PawnsData", []):
        rows.setdefault(e["m_shipID"], [e.get(s) or "" for s in SLOTS])

with open(OUT, "w") as out:
    out.write("// GENERATED by scripts/gen-npc-abilities.py from\n"
              "// data/pve/HVC_DeadHorde_EnemyShips_rows.jsonl -- do not edit.\n"
              "// Havoc NPC ShipId -> ability class paths, row slot order (primary,\n"
              "// secondary, perimeter, internal, extra 1-4); empty = slot unset.\n"
              "#pragma once\n\n"
              "struct NpcAbilities {\n  const char *ship;\n  const wchar_t *path[8];\n};\n\n"
              "static const NpcAbilities kNpcAbilities[] = {\n")
    for ship in sorted(rows):
        paths = ", ".join(f'L"{p}"' for p in rows[ship])
        out.write(f'    {{"{ship}", {{{paths}}}}},\n')
    out.write("};\n")
print(f"wrote {len(rows)} NPC ability rows to {OUT}")
